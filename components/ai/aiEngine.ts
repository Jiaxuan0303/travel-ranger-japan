export async function getAIResponse(
  userMessage: string,
  questContext: QuestContext,
  conversationHistory: AIMessage[]
): Promise<{ content: string; suggestions: string[] }> {
  // 1) 范围检测
  if (userMessage.trim().length > 5 && !isRelevant(userMessage, questContext)) {
    return {
      content: `该问题与当前学习内容无关。\n\n你现在正在学习「**${questContext.questTitle}**」——${questContext.questDescription}\n\n有关于${questContext.cityName}（${questContext.cityNameJa}）旅行和文化的问题尽管问我！`,
      suggestions: [questContext.knowledge[0] || '', questContext.knowledge[1] || ''].filter(Boolean).slice(0, 2),
    };
  }

  // 2) 获取当前任务的知识库
  const questQAEntries = questQA[questContext.questId] || [];
  const cityEntries = cityGeneralQA[questContext.cityName] || [];

  const userTokens = extractKeywords(userMessage);

  // 3) 匹配最佳回答
  let bestMatch: { qa: QAPair; score: number } | null = null;

  for (const qa of questQAEntries) {
    for (const pattern of qa.q) {
      const patternTokens = extractKeywords(pattern);
      const score = matchScore(userTokens, patternTokens);
      if (score > (bestMatch?.score || 0)) {
        bestMatch = { qa, score };
      }
    }
  }

  // 也检查城市通用知识
  for (const qa of cityEntries) {
    for (const pattern of qa.q) {
      const patternTokens = extractKeywords(pattern);
      const score = matchScore(userTokens, patternTokens) + 1; // +1 偏向任务知识
      if (score > (bestMatch?.score || 0)) {
        bestMatch = { qa, score };
      }
    }
  }

  // 4) 生成回答
  if (bestMatch && bestMatch.score >= 2) {
    const usedQuestions = conversationHistory.filter((m) => m.role === 'user').map((m) => m.content);
    const unusedRelated = bestMatch.qa.related.filter(
      (r) => !usedQuestions.some((uq) => uq.includes(r.slice(0, 10)))
    );

    return {
      content: bestMatch.qa.a,
      suggestions: unusedRelated.length > 0 ? unusedRelated.slice(0, 2) : bestMatch.qa.related.slice(0, 2),
    };
  }

  // 5) 兜底回答：提供最相关的知识点
  const allKnowledge = questContext.knowledge;
  if (allKnowledge.length > 0) {
    const fallbackQuestions = questQAEntries.slice(0, 2).flatMap((qa) => qa.related).slice(0, 2);
    return {
      content: `关于「${questContext.questTitle}」，以下是核心知识点：\n\n📌 ${allKnowledge.join('\n\n📌 ')}\n\n你可以针对其中任意一点继续深入提问！比如问我"为什么"或"怎么去"等问题。`,
      suggestions: fallbackQuestions,
    };
  }

  return {
    content: `「${questContext.questTitle}」是一个有趣的话题。你想了解哪方面呢？可以直接问我"是什么"、"怎么去"、"有什么故事"等。`,
    suggestions: ['这个景点有什么历史？', '怎么去这个地方？'],
  };
}
