/** 分词 + 提取关键词 */
function extractKeywords(text: string): string[] {
  const lower = text.toLowerCase();
  // 中文字符按单字切，英文/日文按词切
  const tokens: string[] = [];
  // 提取连续的中文字符
  const chineseChars = lower.match(/[一-鿿]+/g);
  if (chineseChars) tokens.push(...chineseChars.flatMap((s) => s.split('')));
  // 提取英文/日文单词
  const words = lower.match(/[a-z぀-ヿ가-힯]+/g);
  if (words) tokens.push(...words);
  // 保留原文本用于模糊匹配
  tokens.push(lower);
  return tokens.filter((t) => t.length >= 1);
}

/** 计算问题与预设问题的匹配度 */
function matchScore(questionTokens: string[], qaTokens: string[]): number {
  let score = 0;
  for (const qt of questionTokens) {
    for (const at of qaTokens) {
      if (at.length === 0) continue;
      if (qt === at) score += 3;           // 精确匹配
      else if (at.includes(qt) && qt.length >= 2) score += 2;  // 部分包含
      else if (qt.includes(at) && at.length >= 2) score += 1;
    }
  }
  return score;
}

/** 判断问题是否与当前任务相关 */
function isRelevant(question: string, questContext: QuestContext): boolean {
  const q = question.toLowerCase();
  const ctx = (questContext.questTitle + ' ' + questContext.questDescription + ' ' +
    questContext.cityName + ' ' + questContext.cityNameJa + ' ' +
    questContext.knowledge.join(' ')).toLowerCase();

  // 提取上下文关键词
  const ctxWords = extractKeywords(ctx);
  const qWords = extractKeywords(q).filter((w) => w.length >= 2);

  // 至少有一个关键词匹配才认为相关
  const matchCount = qWords.filter((w) => ctxWords.some((cw) => cw.includes(w) || w.includes(cw)));
  return matchCount.length >= 1 || q.length < 8;  // 短问题允许
}

